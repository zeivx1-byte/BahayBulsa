def _income(name, amount, *, regular=True, minimum=None):
    return {"name": name, "monthly_amount": amount, "regular": regular, "minimum_monthly_amount": minimum}


def _debt(name, balance, minimum, rate=None):
    return {"name": name, "balance": balance, "minimum_payment": minimum, "annual_interest_rate_percent": rate}


def _case(number, title, region, location, size, incomes, expenses, fund, hand, *,
          focus, assumptions, bsp, debts=(), goals=(), communicate=(), regression=()):
    annual_income, annual_spending = REGIONAL_ANCHORS[region]
    table, observation = BSP_PATTERNS[bsp]
    return {
        "id": f"X-{number:02d}",
        "title": title,
        "region": region,
        "focus": focus,
        "assumptions": assumptions,
        "source": [
            {"agency": "Philippine Statistics Authority", "survey": "Family Income and Expenditure Survey",
             "year": 2023, "tables": "Press release Tables 1 and 2, preliminary",
             "region": region, "annual_income_thousand_php": annual_income,
             "annual_expenditure_thousand_php": annual_spending,
             "monthly_income_reference_php": round(annual_income * 1000 / 12, 2),
             "monthly_expenditure_reference_php": round(annual_spending * 1000 / 12, 2),
             "reference_method": "Annual averages converted to monthly pesos for scale only.", "url": PSA_URL},
            {"agency": "Bangko Sentral ng Pilipinas", "survey": "Consumer Finance Survey",
             "year": 2021, "table": f"Appendix Table {table}", "aggregate_observation": observation, "url": BSP_URL},
        ],
        "profile": {
            "location": location,
            "household_size": size,
            "incomes": incomes,
            "expenses": [{"name": name, "category": category, "monthly_amount": amount}
                         for name, category, amount in expenses],
            "debts": list(debts),
            "savings_goals": list(goals),
            "emergency_fund_balance": fund,
        },
        "hand_checked": hand,
        "must_communicate": list(communicate),
        "regression_checks": list(regression),
    }


